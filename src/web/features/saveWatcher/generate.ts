import { isUploadToken } from '../../../shared/saveUpload.js';
import bashTemplate from './templates/ficsmap-watch.sh?raw';
import psTemplate from './templates/ficsmap-watch.ps1?raw';
import dockerfileTemplate from './templates/Dockerfile?raw';
import composeTemplate from './templates/docker-compose.yml?raw';
import { zipFiles } from './zip.js';

/**
 * The save watcher's script generator: fills the templates in `templates/` with the user's settings. Every value goes
 * through the quoting of its language (bash and POSIX shell, PowerShell, YAML for Compose), so nothing typed into the
 * form can end a string and become code. Pure; the settings block (`SaveWatcherSection.tsx`) downloads the result.
 */

export type WatchPlatform = 'docker' | 'bash' | 'powershell';
export const WATCH_PLATFORMS: readonly WatchPlatform[] = ['docker', 'bash', 'powershell'];
export type UploadMode = 'newest' | 'all';

export interface WatchConfig {
  /** The ficsmap server's origin (`window.location.origin`). */
  serverUrl: string;
  worldId: string;
  /** The upload token (`fsm_<id>_<secret>`). */
  token: string;
  /** The save folder on the computer or server that runs the script (for Docker: on the Docker host). */
  saveDir: string;
  /** Only saves whose file name starts with `<sessionFilter>_`; empty: every save. */
  sessionFilter: string;
  pollSeconds: number;
  /**
   * At most one accepted upload per this many minutes (0: no limit). A save that comes in sooner waits; when the time
   * is up, the newest waiting save is uploaded and the ones in between are skipped.
   */
  intervalMinutes: number;
  mode: UploadMode;
}

export const POLL_MIN = 5;
export const POLL_MAX = 3600;
export const POLL_DEFAULT = 30;
/** Upload interval in minutes; 0 turns the limit off. */
export const INTERVAL_MIN = 0;
export const INTERVAL_MAX = 1440;
export const INTERVAL_DEFAULT = 30;
/** Folder of the zip for Docker, the image and container name. */
export const DOCKER_NAME = 'ficsmap-watch';

/** Where the script runs. Docker mounts the save folder at /saves and keeps its state in a volume at /state. */
const CONTAINER_SAVES = '/saves';
const CONTAINER_STATE = '/state';

const ORIGIN_RE = /^https?:\/\/[A-Za-z0-9.-]+(:[0-9]{1,5})?$|^https?:\/\/\[[0-9A-Fa-f:.]+\](:[0-9]{1,5})?$/;
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const CONTROL_RE = /[\u0000-\u001f\u007f]/;

export type ConfigProblem = 'serverUrl' | 'worldId' | 'token' | 'saveDir' | 'sessionFilter' | 'pollSeconds' | 'intervalMinutes';

/** What is wrong with a config (empty when it can be rendered). */
export function configProblems(c: WatchConfig): ConfigProblem[] {
  const out: ConfigProblem[] = [];
  if (!ORIGIN_RE.test(c.serverUrl)) out.push('serverUrl');
  if (!UUID_RE.test(c.worldId)) out.push('worldId');
  if (!isUploadToken(c.token)) out.push('token');
  if (c.saveDir.trim() === '' || CONTROL_RE.test(c.saveDir) || c.saveDir.length > 1024) out.push('saveDir');
  if (CONTROL_RE.test(c.sessionFilter) || c.sessionFilter.length > 255) out.push('sessionFilter');
  if (!Number.isInteger(c.pollSeconds) || c.pollSeconds < POLL_MIN || c.pollSeconds > POLL_MAX) out.push('pollSeconds');
  if (!Number.isInteger(c.intervalMinutes) || c.intervalMinutes < INTERVAL_MIN || c.intervalMinutes > INTERVAL_MAX) out.push('intervalMinutes');
  return out;
}

function assertValid(c: WatchConfig): void {
  const problems = configProblems(c);
  if (problems.length > 0) throw new Error(`Invalid save watcher settings: ${problems.join(', ')}`);
}

/** A bash or POSIX shell word: single quotes, a single quote as '\''. */
export function shQuote(s: string): string {
  return `'${s.replaceAll("'", `'\\''`)}'`;
}

/** A PowerShell verbatim string: single quotes, every kind of single quote PowerShell accepts doubled. */
export function psQuote(s: string): string {
  return `'${s.replace(/['‘’‚‛]/g, q => q + q)}'`;
}

/** A YAML single-quoted scalar for Compose: a quote doubled, and `$` doubled so Compose does not interpolate it. */
export function yamlQuote(s: string): string {
  return `'${s.replaceAll("'", "''").replaceAll('$', '$$$$')}'`;
}

/** Replaces each `@@KEY@@` (the values are already quoted); fails when a placeholder is left or unknown. */
export function fill(template: string, values: Record<string, string>): string {
  const out = template.replace(/@@([A-Z_]+)@@/g, (m, key: string) => {
    const v = values[key];
    if (v === undefined) throw new Error(`No value for ${m}`);
    return v;
  });
  return out;
}

function generatedLine(c: WatchConfig, now: Date): string {
  return `Generated by ficsmap (${c.serverUrl}) on ${now.toISOString().slice(0, 10)} for world ${c.worldId}.`;
}

/** The bash script; `docker` points it at the container's /saves and /state. */
export function renderBash(c: WatchConfig, opts: { docker?: boolean; now?: Date } = {}): string {
  assertValid(c);
  const docker = opts.docker ?? false;
  return fill(bashTemplate.replaceAll('\r\n', '\n'), {
    GENERATED: generatedLine(c, opts.now ?? new Date()),
    SERVER_URL: shQuote(c.serverUrl),
    WORLD_ID: shQuote(c.worldId),
    TOKEN: shQuote(c.token),
    SAVE_DIR: shQuote(docker ? CONTAINER_SAVES : c.saveDir.trim()),
    SESSION: shQuote(c.sessionFilter),
    POLL_SECONDS: String(c.pollSeconds),
    INTERVAL_MINUTES: String(c.intervalMinutes),
    MODE: shQuote(c.mode),
    STATE_DIR: shQuote(docker ? CONTAINER_STATE : ''),
  });
}

/** The PowerShell script, with Windows line ends. */
export function renderPowerShell(c: WatchConfig, opts: { now?: Date } = {}): string {
  assertValid(c);
  return fill(psTemplate.replaceAll('\r\n', '\n'), {
    GENERATED: generatedLine(c, opts.now ?? new Date()),
    SERVER_URL: psQuote(c.serverUrl),
    WORLD_ID: psQuote(c.worldId),
    TOKEN: psQuote(c.token),
    SAVE_DIR: psQuote(c.saveDir.trim()),
    SESSION: psQuote(c.sessionFilter),
    POLL_SECONDS: String(c.pollSeconds),
    INTERVAL_MINUTES: String(c.intervalMinutes),
    MODE: psQuote(c.mode),
    STATE_DIR: psQuote(''),
  }).replaceAll('\n', '\r\n');
}

/** The Compose file: builds the image from the folder and mounts the save folder read-only. */
export function renderCompose(c: WatchConfig): string {
  assertValid(c);
  return fill(composeTemplate.replaceAll('\r\n', '\n'), { SAVE_DIR: yamlQuote(c.saveDir.trim()) });
}

export interface WatcherDownload {
  fileName: string;
  mime: string;
  data: Uint8Array;
}

/**
 * The file to download: the bash script, the PowerShell script (UTF-8 with BOM, so Windows PowerShell 5.1 reads
 * names with umlauts right), or for Docker a zip with Dockerfile, script and Compose file in `ficsmap-watch/`.
 */
export function watcherDownload(platform: WatchPlatform, c: WatchConfig, now = new Date()): WatcherDownload {
  const enc = new TextEncoder();
  if (platform === 'bash') return { fileName: 'ficsmap-watch.sh', mime: 'text/x-shellscript', data: enc.encode(renderBash(c, { now })) };
  if (platform === 'powershell') {
    return { fileName: 'ficsmap-watch.ps1', mime: 'text/plain', data: enc.encode(`﻿${renderPowerShell(c, { now })}`) };
  }
  const data = zipFiles([
    { name: `${DOCKER_NAME}/Dockerfile`, data: enc.encode(dockerfileTemplate.replaceAll('\r\n', '\n')) },
    { name: `${DOCKER_NAME}/ficsmap-watch.sh`, data: enc.encode(renderBash(c, { docker: true, now })), executable: true },
    { name: `${DOCKER_NAME}/docker-compose.yml`, data: enc.encode(renderCompose(c)) },
  ], now);
  return { fileName: `${DOCKER_NAME}.zip`, mime: 'application/zip', data };
}

/** The host side of `-v` for `docker run`: `~/…` keeps working inside the quotes through "$HOME". */
function dockerVolume(saveDir: string): string {
  const dir = saveDir.trim();
  if (dir === '~' || dir.startsWith('~/')) return `"$HOME"${shQuote(`${dir.slice(1)}:${CONTAINER_SAVES}:ro`)}`;
  return shQuote(`${dir}:${CONTAINER_SAVES}:ro`);
}

/** How to run the downloaded file: one entry per step, `id` names the step's label in the UI. */
/**
 * Steam launch options that run the watcher while the game runs: it starts with the game, logs to
 * ~/ficsmap/watch.log and stops a minute after the game exits. `env -i` gives the watcher a clean environment, so
 * Steam's library paths (its old libcurl, 32-bit overlay preloads) never reach curl.
 */
export const STEAM_LAUNCH_OPTIONS =
  `bash -c 'env -i HOME="$HOME" PATH=/usr/local/bin:/usr/bin:/bin "$HOME/ficsmap/ficsmap-watch.sh" >>"$HOME/ficsmap/watch.log" 2>&1 & w=$!; "$@"; s=$?; sleep 60; kill $w; exit $s' _ %command%`;

export function runSteps(platform: WatchPlatform, c: WatchConfig): { id: 'run' | 'steamInstall' | 'steam' | 'compose' | 'dockerRun' | 'autostart'; code: string }[] {
  if (platform === 'bash') {
    return [
      { id: 'run', code: 'chmod +x ficsmap-watch.sh && ./ficsmap-watch.sh' },
      { id: 'steamInstall', code: 'mkdir -p ~/ficsmap && mv ficsmap-watch.sh ~/ficsmap/ && chmod +x ~/ficsmap/ficsmap-watch.sh' },
      { id: 'steam', code: STEAM_LAUNCH_OPTIONS },
    ];
  }
  if (platform === 'powershell') {
    return [
      { id: 'run', code: 'powershell -ExecutionPolicy Bypass -File ficsmap-watch.ps1' },
      {
        id: 'autostart',
        code: [
          '$script = "$env:USERPROFILE\\ficsmap\\ficsmap-watch.ps1"',
          '$action = New-ScheduledTaskAction -Execute \'powershell.exe\' -Argument "-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$script`""',
          '$trigger = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME',
          '$settings = New-ScheduledTaskSettingsSet -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1)',
          'Register-ScheduledTask -TaskName \'ficsmap save watcher\' -Action $action -Trigger $trigger -Settings $settings',
        ].join('\n'),
      },
    ];
  }
  return [
    { id: 'compose', code: `unzip ${DOCKER_NAME}.zip && cd ${DOCKER_NAME} && docker compose up -d --build` },
    {
      id: 'dockerRun',
      code: `cd ${DOCKER_NAME} && docker build -t ${DOCKER_NAME} . && docker run -d --name ${DOCKER_NAME} --restart unless-stopped -v ${dockerVolume(c.saveDir)} -v ${DOCKER_NAME}-state:${CONTAINER_STATE} ${DOCKER_NAME}`,
    },
  ];
}
